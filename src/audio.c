static int current_room=-1;
static int audio_tick=0;
static int pulse_flip=0;

static void upload(uint32_t addr,const uint8_t *data,int size){
  SpuSetTransferStartAddr(addr);
  SpuWrite((const uint32_t*)data,(size+63)&~63);
  SpuIsTransferCompleted(SPU_TRANSFER_WAIT);
}

void moko_audio_init(void){
  SpuInit();
  upload(SFX_CLICK_ADDR,click_adpcm,sizeof(click_adpcm));
  upload(SFX_IMPACT_ADDR,impact_adpcm,sizeof(impact_adpcm));
  upload(SFX_CHIME_ADDR,chime_adpcm,sizeof(chime_adpcm));
  upload(SFX_ALARM_ADDR,alarm_adpcm,sizeof(alarm_adpcm));
  upload(AMB_ADDR,ambience_adpcm,sizeof(ambience_adpcm));
  upload(PULSE_ADDR,pulse_adpcm,sizeof(pulse_adpcm));
  SPU_CH_ADSR1(0)=0x00ff;SPU_CH_ADSR2(0)=0;
  SPU_CH_ADSR1(1)=0x00ff;SPU_CH_ADSR2(1)=0;
  SPU_CH_ADSR1(2)=0x00ff;SPU_CH_ADSR2(2)=0;
  SPU_CH_VOL_L(0)=0x2800;SPU_CH_VOL_R(0)=0x2800;
  SPU_CH_VOL_L(1)=0x0900;SPU_CH_VOL_R(1)=0x0900;
  SPU_CH_VOL_L(2)=0x0700;SPU_CH_VOL_R(2)=0x0700;
  SPU_CH_ADDR(0)=getSPUAddr(SFX_CLICK_ADDR);
  SPU_CH_ADDR(1)=getSPUAddr(AMB_ADDR);
  SPU_CH_ADDR(2)=getSPUAddr(PULSE_ADDR);
}

void moko_audio_sfx(int pitch){
  uint32_t addr=SFX_CLICK_ADDR;
  int volume=0x2500;
  /* Existing gameplay pitches now select different timbres automatically. */
  if(pitch>=0x2300){addr=SFX_CHIME_ADDR;volume=0x2b00;}
  else if(pitch>=0x1900){addr=SFX_IMPACT_ADDR;volume=0x2d00;}
  else if(pitch<=0x0d00){addr=SFX_ALARM_ADDR;volume=0x2200;}
  SPU_CH_VOL_L(0)=volume;SPU_CH_VOL_R(0)=volume;
  SpuSetKey(0,1u<<0);
  SPU_CH_FREQ(0)=pitch;
  SPU_CH_ADDR(0)=getSPUAddr(addr);
  SpuSetKey(1,1u<<0);
}

void moko_audio_set_room(int room){
  static const uint16_t pitch[5]={0x0b00,0x0d00,0x0900,0x1000,0x0800};
  if(room<0||room>4||room==current_room)return;
  current_room=room;audio_tick=0;pulse_flip=0;
  SpuSetKey(0,(1u<<1)|(1u<<2));
  SPU_CH_FREQ(1)=pitch[room];
  SPU_CH_ADDR(1)=getSPUAddr(AMB_ADDR);
  SPU_CH_VOL_L(1)=0x0700+room*0x100;
  SPU_CH_VOL_R(1)=0x0b00-room*0x100;
  SpuSetKey(1,1u<<1);
  /* Audible room-entry clock cue. */
  SPU_CH_FREQ(2)=0x1000+room*0x180;
  SPU_CH_ADDR(2)=getSPUAddr(SFX_CHIME_ADDR);
  SPU_CH_VOL_L(2)=0x0d00;SPU_CH_VOL_R(2)=0x0d00;
  SpuSetKey(1,1u<<2);
}

void moko_audio_tick(void){
  static const uint16_t pulse_pitch[5]={0x1500,0x1200,0x0d00,0x1800,0x0900};
  int interval;
  if(current_room<0)return;
  audio_tick++;
  interval=210-current_room*24;
  if(current_room==4)interval=96; /* Clock Chamber feels more urgent. */
  if(audio_tick>=interval){
    audio_tick=0;pulse_flip^=1;
    SpuSetKey(0,1u<<2);
    SPU_CH_FREQ(2)=pulse_pitch[current_room]+(pulse_flip?0x0180:0);
    SPU_CH_ADDR(2)=getSPUAddr(PULSE_ADDR);
    SPU_CH_VOL_L(2)=pulse_flip?0x0900:0x0500;
    SPU_CH_VOL_R(2)=pulse_flip?0x0500:0x0900;
    SpuSetKey(1,1u<<2);
  }
}
